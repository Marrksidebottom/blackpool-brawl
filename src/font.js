const cache = new Map();

function glyphCanvas(ch, color) {
  const key = ch + '|' + color;
  let c = cache.get(key);
  if (c) return c;
  const rows = RAW[ch] || RAW['?'];
  c = document.createElement('canvas');
  c.width = 3;
  c.height = 5;
  const g = c.getContext('2d');
  g.fillStyle = color;
  for (let y = 0; y < 5; y++) for (let x = 0; x < 3; x++) if (rows[y][x] === '1') g.fillRect(x, y, 1, 1);
  cache.set(key, c);
  return c;
}

export function textWidth(str, scale = 1) {
  return str.length ? (str.length * 4 - 1) * scale : 0;
}

function raw(ctx, str, x, y, color, scale) {
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    if (ch !== ' ') ctx.drawImage(glyphCanvas(ch, color), x + i * 4 * scale, y, 3 * scale, 5 * scale);
  }
}

/**
 * Draw pixel text. opts: color, scale, align ('left'|'center'|'right'), outline colour (or null).
 */
export function drawText(ctx, str, x, y, opts = {}) {
  const { color = '#fff', scale = 1, align = 'left', outline = '#000' } = opts;
  str = String(str).toUpperCase();
  const w = textWidth(str, scale);
  let sx = x;
  if (align === 'center') sx = x - Math.floor(w / 2);
  else if (align === 'right') sx = x - w;
  sx = Math.round(sx);
  y = Math.round(y);
  if (outline) {
    const s = scale;
    raw(ctx, str, sx - s, y, outline, scale);
    raw(ctx, str, sx + s, y, outline, scale);
    raw(ctx, str, sx, y - s, outline, scale);
    raw(ctx, str, sx, y + s, outline, scale);
    raw(ctx, str, sx + s, y + s, outline, scale);
  }
  raw(ctx, str, sx, y, color, scale);
  return w;
}
